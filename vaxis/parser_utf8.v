struct InputUtf8Iterator {
	bytes []u8
mut:
	i int
}

fn (mut iter InputUtf8Iterator) next() ?u32 {
	if iter.i >= iter.bytes.len { return none }
	mut cp := u32(0)
	mut state := 0
	for {
		byte := iter.bytes[iter.i]
		class := input_utf8d[int(byte)]
		cp = if state != 0 { u32(byte & 0x3f) | (cp << 6) } else { (u32(0xff) >> class) & u32(byte) }
		state = int(input_state_utf8d[state + int(class)])
		iter.i++
		if state == 0 || state == 12 || iter.i >= iter.bytes.len { break
		 }
	}
	return if state == 0 { cp } else { u32(0xfffd) }
}
