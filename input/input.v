module input

import oniguruma

// KeyEvent represents a keyboard event.
// This is a generic key input event that provides the information needed
// regardless of apprt to generate proper terminal control sequences.
pub struct KeyEvent {
pub mut:
	// The action: press, release, etc.
	action KeyAction = .press
	// The keycode of the physical key that was pressed. Layout-independent.
	key Key = .unidentified
	// Modifiers that are pressed.
	mods Mods
	// The mods that were consumed in order to generate the text in utf8.
	consumed_mods Mods
	// True when this key event is part of a dead key composition sequence.
	composing bool
	// The utf8 sequence generated by this key event. Empty if no text generated.
	utf8 string
	// The codepoint for this key when unshifted (e.g. shift+a -> unshifted is 'a').
	unshifted_codepoint u32
}

// effective_mods returns the mods that should be considered for keybindings.
pub fn (e KeyEvent) effective_mods() Mods {
	if e.utf8.len == 0 {
		return e.mods
	}
	return e.mods.unset(e.consumed_mods)
}

// binding_hash returns a unique hash for this key event for binding tracking.
pub fn (e KeyEvent) binding_hash() u64 {
	mut hasher := SourceHash{}
	// Key is enum(c_int), the codepoint is u21, and Mods is packed u16.
	hasher.put_i32(i32(e.key))
	hasher.put_u21(e.unshifted_codepoint)
	hasher.put_u16(e.mods.binding().int())
	return hasher.final()
}

// KeyAction represents the action type of a key event.
pub enum KeyAction {
	release
	press
	repeat
}

// Side represents which side (left or right) a modifier key is on.
pub enum Side as u8 {
	left  = 0
	right = 1
}

// SideInfo tracks which side modifier keys are pressed on.
pub struct SideInfo {
pub mut:
	shift Side
	ctrl  Side
	alt   Side
	super Side
}

// Mods is a bitmask for all key modifiers.
pub struct Mods {
pub mut:
	shift     bool
	ctrl      bool
	alt       bool
	super_    bool
	caps_lock bool
	num_lock  bool
	sides     SideInfo
}

// int returns the integer value of the modifier bitmask.
//
// Faithful to Zig's packed `Mods` bitcast layout:
//   bit 0: shift, 1: ctrl, 2: alt, 3: super,
//   bit 4: caps_lock, 5: num_lock,
//   bit 6: sides.shift, 7: sides.ctrl, 8: sides.alt, 9: sides.super
// where each side bit is 0 for left (and none_) and 1 for right.
pub fn (m Mods) int() u16 {
	mut v := u16(0)
	if m.shift {
		v |= 1
	}
	if m.ctrl {
		v |= 2
	}
	if m.alt {
		v |= 4
	}
	if m.super_ {
		v |= 8
	}
	if m.caps_lock {
		v |= 16
	}
	if m.num_lock {
		v |= 32
	}
	if m.sides.shift == .right {
		v |= 64
	}
	if m.sides.ctrl == .right {
		v |= 128
	}
	if m.sides.alt == .right {
		v |= 256
	}
	if m.sides.super == .right {
		v |= 512
	}
	return v
}

// empty returns true if no modifiers are set.
pub fn (m Mods) empty() bool {
	return m.int() == 0
}

// equal returns true if two mods are equal.
pub fn (a Mods) equal(b Mods) bool {
	return a.int() == b.int()
}

// binding returns only the binding-relevant modifiers.
pub fn (m Mods) binding() Mods {
	return Mods{
		shift: m.shift
		ctrl: m.ctrl
		alt: m.alt
		super_: m.super_
	}
}

// unset performs self &~ other to remove the other mods from self.
//
// Faithful to Zig `Mods.unset`: `@bitCast(self.int() & ~other.int())`, so the
// operation is a pure bitmask over the full packed layout, preserving the
// side and lock bits that `other` does not clear.
pub fn (self Mods) unset(other Mods) Mods {
	return mods_from_int(self.int() & ~other.int())
}

