// Momentum represents the "momentum" of a mouse scroll event.
// Used to handle "inertial scrolling" (i.e. flicking).
// https://developer.apple.com/documentation/appkit/nseventphase
pub enum Momentum as u8 {
	none_
	began
	stationary
	changed
	ended
	cancelled
	may_begin
}

// PressureStage represents the pressure stage of a pressure-sensitive input device.
pub enum PressureStage as u8 {
	none_ // The input device is unpressed.
	normal // Normal press amount (after a "click" on macOS trackpads).
	deep // Deep press amount (after a "force click" on macOS trackpads).
}

// ScrollMods contains additional information about a scroll event.
pub struct ScrollMods {
pub mut:
	// Whether this is a precision scroll (e.g. trackpad).
	precision bool
	// The momentum phase of the scroll event.
	momentum Momentum = .none_
}

// scroll_mods_from_int decodes ScrollMods' packed u8 ABI. Ghostty stores the
// precision flag in bit 0 and the three-bit Momentum value in bits 1 through 3.
pub fn scroll_mods_from_int(raw u8) ScrollMods {
	momentum := match (raw >> 1) & 0x7 {
		1 { Momentum.began }
		2 { Momentum.stationary }
		3 { Momentum.changed }
		4 { Momentum.ended }
		5 { Momentum.cancelled }
		6 { Momentum.may_begin }
		else { Momentum.none_ }
	}
	return ScrollMods{
		precision: raw & 0x1 != 0
		momentum: momentum
	}
}

// int returns ScrollMods' packed u8 ABI representation.
pub fn (self ScrollMods) int() u8 {
	momentum := match self.momentum {
		.none_ { u8(0) }
		.began { u8(1) }
		.stationary { u8(2) }
		.changed { u8(3) }
		.ended { u8(4) }
		.cancelled { u8(5) }
		.may_begin { u8(6) }
	}
	return u8(self.precision) | (momentum << 1)
}

// OptionAsAlt determines whether the "option" key on macOS is treated
// as "alt" or not. See the Ghostty `macos_option-as-alt` config
// docs for a more detailed description of why this is needed.
pub enum OptionAsAlt {
	false_ // don't treat option as alt (macOS default)
	true_ // treat both options as alt
	left // treat left option as alt
	right // treat right option as alt
}

// Link matching.
pub struct Link {
pub:
	regex     string
	action    LinkAction
	highlight LinkHighlight
	// Used by the *_mods highlight variants. Zig represents these variants as
	// tagged-union payloads; V keeps the payload beside the enum tag.
	mods Mods
}

// oni_regex compiles the configured expression for renderer link matching.
pub fn (self &Link) oni_regex() !oniguruma.Regex {
	return oniguruma.Regex.init(self.regex, oniguruma.Options{}, .utf8, .default_, none)
}

// clone returns an independently owned copy of the link configuration.
pub fn (self &Link) clone() Link {
	return Link{
		regex: self.regex.clone()
		action: self.action
		highlight: self.highlight
		mods: if self.highlight in [.always_mods, .hover_mods] { self.mods } else { Mods{} }
	}
}

// equal compares the action, highlight payload, and regular expression.
pub fn (self &Link) equal(other Link) bool {
	if self.action != other.action || self.highlight != other.highlight || self.regex != other.regex {
		return false
	}
	return self.highlight !in [.always_mods, .hover_mods] || self.mods.equal(other.mods)
}

pub enum LinkAction {
	open
	open_osc8
}

pub enum LinkHighlight {
	always
	hover
	always_mods
	hover_mods
}

// PasteOptions contains options that affect paste encoding.
pub struct PasteOptions {
pub:
	// True if bracketed paste mode is on.
	bracketed bool
}

// paste_encode encodes data for pasting into the terminal.
// Returns an array of 3 string slices that, when concatenated, form the
// complete paste sequence.
pub fn paste_encode(data string, opts PasteOptions) [3]string {
	// Bracketed paste mode wraps pasted data in fenceposts
	if opts.bracketed {
		return ['\x1b[200~', data, '\x1b[201~']!
	}
	// Non-bracketed: replace newlines with carriage returns
	return ['', data.replace('\n', '\r'), '']!
}

// paste_is_safe returns true if data is safe to paste.
// Data is considered unsafe if it contains newlines or the
// bracketed paste end sequence.
pub fn paste_is_safe(data string) bool {
	if data.contains('\n') {
		return false
	}
	if data.contains('\x1b[201~') {
		return false
	}
	return true
}

// KeyboardLayout represents a detected keyboard layout.
pub enum KeyboardLayout {
	unknown
	us_standard
	us_international
	abc
	dvorak
	colemak
}

// map_apple_id maps an Apple keyboard layout source ID to a KeyboardLayout.
pub fn KeyboardLayout.map_apple_id(id string) ?KeyboardLayout {
	if id == 'com.apple.keylayout.US' {
		return .us_standard
	}
	if id == 'com.apple.keylayout.USInternational' {
		return .us_international
	}
	return none
}

// detect_option_as_alt returns the recommended OptionAsAlt setting
// for this keyboard layout.
pub fn (l KeyboardLayout) detect_option_as_alt() OptionAsAlt {
	return match l {
		.us_standard, .us_international { .true_ }
		else { .false_ }
	}
}

// translation returns the mods to use for key translation. This handles
// settings like macos-option-as-alt. The translation mods should be used
// for translation but never sent back in for the key callback.
//
// Faithful to Zig `Mods.translation` in key_mods.zig: on Darwin, alt is
// unset unless option-as-alt is disabled (.false_) or the pressed option
// key is on the side that should NOT be treated as alt.
pub fn (m Mods) translation(option_as_alt OptionAsAlt) Mods {
	mut result := m
	$if darwin {
		// Determine whether to unset alt. We keep alt (skip unsetting) when
		// option-as-alt is disabled or the active side is the "wrong" side.
		unset_alt := match option_as_alt {
			.false_ { false }
			.true_ { true }
			.left { m.sides.alt != .right }
			.right { m.sides.alt != .left }
		}
		if unset_alt {
			result.alt = false
		}
	}
	return result
}

