// PasteOptions contains options that affect paste encoding.
pub struct PasteOptions {
pub:
	// True if bracketed paste mode is on.
	bracketed bool
}

// paste_encode encodes data for pasting into the terminal.
// Returns an array of 3 string slices that, when concatenated, form the
// complete paste sequence.
pub fn paste_encode(data string, opts PasteOptions) [3]string {
	// Bracketed paste mode wraps pasted data in fenceposts
	if opts.bracketed {
		return ['\x1b[200~', data, '\x1b[201~']!
	}
	// Non-bracketed: replace newlines with carriage returns
	return ['', data.replace('\n', '\r'), '']!
}

// paste_is_safe returns true if data is safe to paste.
// Data is considered unsafe if it contains newlines or the
// bracketed paste end sequence.
pub fn paste_is_safe(data string) bool {
	if data.contains('\n') {
		return false
	}
	if data.contains('\x1b[201~') {
		return false
	}
	return true
}

// Keymap handles mapping between physical keycodes and logical keys.
// On macOS this wraps the keyboard layout system.
pub struct Keymap {
pub mut:
	// Internal state for the keymap.
	state voidptr
}

pub fn Keymap.init() !Keymap {
	state := C.witty_keymap_current_source()
	if state == unsafe { nil } {
		return error('failed to get keyboard input source')
	}
	return Keymap{ state: state }
}

pub fn (mut k Keymap) deinit() {
	if k.state != unsafe { nil } {
		C.witty_keymap_release(k.state)
	}
	k.state = unsafe { nil }
}

pub fn (mut k Keymap) reload() ! {
	new_state := C.witty_keymap_current_source()
	if new_state == unsafe { nil } {
		return error('failed to get keyboard input source')
	}
	if k.state != unsafe { nil } {
		C.witty_keymap_release(k.state)
	}
	k.state = new_state
}

// source_id returns the keyboard layout source identifier.
pub fn (k Keymap) source_id(mut buf []u8) !string {
	if buf.len == 0 {
		return error('keyboard source ID buffer is empty')
	}
	if C.witty_keymap_source_id(k.state, unsafe { &char(buf.data) }, usize(buf.len)) != 0 {
		return error('keyboard source ID does not fit in buffer')
	}
	return unsafe { cstring_to_vstring(&char(buf.data)) }
}

// KeymapState is the opaque state threaded through consecutive translations.
// A non-zero dead_key means the current input is composing.
pub struct KeymapState {
pub mut:
	dead_key u32
}

pub struct KeymapTranslation {
pub:
	text      string
	composing bool
	mods      Mods
}

// translate maps a native macOS virtual key code through the selected input
// source. Ctrl is deliberately removed before Carbon translation so Ctrl+C
// produces "c", not the control character 0x03; the original modifiers are
// otherwise returned after that consumption step.
pub fn (k Keymap) translate(mut out []u8, mut state KeymapState, code u16, input_mods Mods) !KeymapTranslation {
	if out.len == 0 {
		return error('keyboard translation buffer is empty')
	}
	mut mods := input_mods
	mods.ctrl = false
	modifier_state := (u32(if mods.super_ { 1 } else { 0 }) | u32(if mods.shift {
		1 << 1
	} else {
		0
	}) | u32(if mods.caps_lock {
		1 << 2
	} else {
		0
	}) | u32(if mods.alt { 1 << 3 } else { 0 }))
	mut composing := 0
	if C.witty_keymap_translate(k.state, code, modifier_state, &state.dead_key, unsafe { &char(out.data) }, usize(out.len), &composing) != 0 {
		return error('keyboard translation failed')
	}
	return KeymapTranslation{
		text: unsafe { cstring_to_vstring(&char(out.data)) }
		composing: composing != 0
		mods: mods
	}
}

// KeyboardLayout represents a detected keyboard layout.
pub enum KeyboardLayout {
	unknown
	us_standard
	us_international
	abc
	dvorak
	colemak
}

// map_apple_id maps an Apple keyboard layout source ID to a KeyboardLayout.
pub fn KeyboardLayout.map_apple_id(id string) ?KeyboardLayout {
	if id == 'com.apple.keylayout.US' {
		return .us_standard
	}
	if id == 'com.apple.keylayout.USInternational' {
		return .us_international
	}
	return none
}

// detect_option_as_alt returns the recommended OptionAsAlt setting
// for this keyboard layout.
pub fn (l KeyboardLayout) detect_option_as_alt() OptionAsAlt {
	return match l {
		.us_standard, .us_international { .true_ }
		else { .false_ }
	}
}

// translation returns the mods to use for key translation. This handles
// settings like macos-option-as-alt. The translation mods should be used
// for translation but never sent back in for the key callback.
//
// Faithful to Zig `Mods.translation` in key_mods.zig: on Darwin, alt is
// unset unless option-as-alt is disabled (.false_) or the pressed option
// key is on the side that should NOT be treated as alt.
pub fn (m Mods) translation(option_as_alt OptionAsAlt) Mods {
	mut result := m
	$if darwin {
		// Determine whether to unset alt. We keep alt (skip unsetting) when
		// option-as-alt is disabled or the active side is the "wrong" side.
		unset_alt := match option_as_alt {
			.false_ { false }
			.true_ { true }
			.left { m.sides.alt != .right }
			.right { m.sides.alt != .left }
		}
		if unset_alt {
			result.alt = false
		}
	}
	return result
}

