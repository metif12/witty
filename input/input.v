}

pub enum LinkAction {
	open
	open_osc8
}

pub enum LinkHighlight {
	always
	hover
	always_mods
	hover_mods
}

// Paste encoding.
pub fn paste_encode(data string, bracketed bool) string {
	if bracketed {
		return '\x1b[200~${data}\x1b[201~'
	}
	return data
}

pub fn paste_is_unsafe(data string, bracketed bool) bool {
	if data.contains('\n') && !bracketed {
		return true
	}
	return false
}
