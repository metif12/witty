module input

import oniguruma

// KeyEvent represents a keyboard event.
// This is a generic key input event that provides the information needed
// regardless of apprt to generate proper terminal control sequences.
pub struct KeyEvent {
pub mut:
	// The action: press, release, etc.
	action KeyAction = .press
	// The keycode of the physical key that was pressed. Layout-independent.
	key Key = .unidentified
	// Modifiers that are pressed.
	mods Mods
	// The mods that were consumed in order to generate the text in utf8.
	consumed_mods Mods
	// True when this key event is part of a dead key composition sequence.
	composing bool
	// The utf8 sequence generated by this key event. Empty if no text generated.
	utf8 string
	// The codepoint for this key when unshifted (e.g. shift+a -> unshifted is 'a').
	unshifted_codepoint u32
}

// effective_mods returns the mods that should be considered for keybindings.
pub fn (e KeyEvent) effective_mods() Mods {
	if e.utf8.len == 0 {
		return e.mods
	}
	return e.mods.unset(e.consumed_mods)
}

// binding_hash returns a unique hash for this key event for binding tracking.
pub fn (e KeyEvent) binding_hash() u64 {
	mut hasher := SourceHash{}
	// Key is enum(c_int), the codepoint is u21, and Mods is packed u16.
	hasher.put_i32(i32(e.key))
	hasher.put_u21(e.unshifted_codepoint)
	hasher.put_u16(e.mods.binding().int())
	return hasher.final()
}

// KeyAction represents the action type of a key event.
pub enum KeyAction as i32 {
	release
	press
	repeat
}

// Side represents which side (left or right) a modifier key is on.
pub enum Side as u8 {
	left  = 0
	right = 1
}

// SideInfo tracks which side modifier keys are pressed on. Ghostty retains
// this as a packed u4; V's narrowest addressable backing integer is u8.
pub struct SideInfo {
mut:
	value u8
}

pub fn SideInfo.init(shift Side, ctrl Side, alt Side, super_ Side) SideInfo {
	return SideInfo{
		value: u8(shift) | (u8(ctrl) << 1) | (u8(alt) << 2) | (u8(super_) << 3)
	}
}

pub fn SideInfo.from_int(value u8) SideInfo {
	return SideInfo{
		value: value & 0x0f
	}
}

pub fn (s SideInfo) int() u8 {
	return s.value
}

pub fn (s SideInfo) shift() Side {
	return if s.value & 1 != 0 { .right } else { .left }
}

pub fn (s SideInfo) ctrl() Side {
	return if s.value & 2 != 0 { .right } else { .left }
}

pub fn (s SideInfo) alt() Side {
	return if s.value & 4 != 0 { .right } else { .left }
}

pub fn (s SideInfo) super_() Side {
	return if s.value & 8 != 0 { .right } else { .left }
}

// Mods is Ghostty's complete packed public modifier ABI, retained as its u16
// backing value. Bits 10 through 15 are padding but remain part of bitcasts.
pub struct Mods {
mut:
	value u16
}

pub fn Mods.init(shift bool, ctrl bool, alt bool, super_ bool, caps_lock bool, num_lock bool, sides SideInfo) Mods {
	mut value := u16(sides.int() & 0x0f) << 6
	if shift {
		value |= 1
	}
	if ctrl {
		value |= 2
	}
	if alt {
		value |= 4
	}
	if super_ {
		value |= 8
	}
	if caps_lock {
		value |= 16
	}
	if num_lock {
		value |= 32
	}
	return Mods{
		value: value
	}
}

pub fn Mods.from_int(value u16) Mods {
	return Mods{
		value: value
	}
}

pub fn (m Mods) shift() bool {
	return m.value & 1 != 0
}

pub fn (m Mods) ctrl() bool {
	return m.value & 2 != 0
}

pub fn (m Mods) alt() bool {
	return m.value & 4 != 0
}

pub fn (m Mods) super_() bool {
	return m.value & 8 != 0
}

pub fn (m Mods) caps_lock() bool {
	return m.value & 16 != 0
}

pub fn (m Mods) num_lock() bool {
	return m.value & 32 != 0
}

pub fn (m Mods) sides() SideInfo {
	return SideInfo.from_int(u8((m.value >> 6) & 0x0f))
}

pub fn (mut m Mods) set_shift(value bool) {
	if value {
		m.value |= 1
	} else {
		m.value &= ~u16(1)
	}
}

pub fn (mut m Mods) set_ctrl(value bool) {
	if value {
		m.value |= 2
	} else {
		m.value &= ~u16(2)
	}
}

pub fn (mut m Mods) set_alt(value bool) {
	if value {
		m.value |= 4
	} else {
		m.value &= ~u16(4)
	}
}

pub fn (mut m Mods) set_super(value bool) {
	if value {
		m.value |= 8
	} else {
		m.value &= ~u16(8)
	}
}

pub fn (mut m Mods) set_caps_lock(value bool) {
	if value {
		m.value |= 16
	} else {
		m.value &= ~u16(16)
	}
}

pub fn (mut m Mods) set_num_lock(value bool) {
	if value {
		m.value |= 32
	} else {
		m.value &= ~u16(32)
	}
}

fn (mut m Mods) set_side(bit u16, side Side) {
	if side == .right {
		m.value |= bit
	} else {
		m.value &= ~bit
	}
}

pub fn (mut m Mods) set_side_shift(side Side) {
	m.set_side(64, side)
}

pub fn (mut m Mods) set_side_ctrl(side Side) {
	m.set_side(128, side)
}

pub fn (mut m Mods) set_side_alt(side Side) {
	m.set_side(256, side)
}

pub fn (mut m Mods) set_side_super(side Side) {
	m.set_side(512, side)
}

// int returns the integer value of the modifier bitmask.
//
pub fn (m Mods) int() u16 {
	return m.value
}

// empty returns true if no modifiers are set.
pub fn (m Mods) empty() bool {
	return m.int() == 0
}

// equal returns true if two mods are equal.
pub fn (a Mods) equal(b Mods) bool {
	return a.int() == b.int()
}

// binding returns only the binding-relevant modifiers.
pub fn (m Mods) binding() Mods {
	return Mods.from_int(m.value & 0x000f)
}

// unset performs self &~ other to remove the other mods from self.
//
// Faithful to Zig `Mods.unset`: `@bitCast(self.int() & ~other.int())`, so the
// operation is a pure bitmask over the full packed layout, preserving the
// side and lock bits that `other` does not clear.
pub fn (self Mods) unset(other Mods) Mods {
	return Mods.from_int(self.int() & ~other.int())
}

