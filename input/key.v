// mod_alias returns the canonical modifier name for an alias.
// Returns none if the string is not a known alias.
fn mod_alias(name string) ?string {
	return match name {
		'cmd' { 'super_' }
		'command' { 'super_' }
		'opt' { 'alt' }
		'option' { 'alt' }
		'control' { 'ctrl' }
		else { none }
	}
}
