module unicode

import os

// Compiler-storage adaptation of the unchanged dependency's Table2 input.
// The layout and lookup expression come from uucode types.Table2/get.data;
// the values are regenerated independently by the native reference probe.
const buildtime_data = $embed_file('@VMODROOT/build_assets/unicode/uucode-buildtime.bin').to_bytes()
const buildtime_stage1_count = 4352

fn uucode_buildtime(cp u32) u16 {
	assert cp <= 0x10ffff
	offset := int(cp >> 8) * 2
	stage1 := u16(buildtime_data[offset]) | (u16(buildtime_data[offset + 1]) << 8)
	index := (buildtime_stage1_count + int(stage1) + int(cp & 0xff)) * 2
	return u16(buildtime_data[index]) | (u16(buildtime_data[index + 1]) << 8)
}

// src/unicode/props_uucode.zig get, including the entire out-of-Unicode u21
// range which contributes to the source generated table's last blocks.
pub fn props_uucode(cp u32) Properties {
	if cp > 0x10ffff { return Properties.from_int(1) }
	return Properties.from_int(u8(uucode_buildtime(cp)))
}

pub struct PropsGeneratorContext {}
pub fn (_ PropsGeneratorContext) get(cp u32) !Properties { return props_uucode(cp) }
pub fn (_ PropsGeneratorContext) eql(a Properties, b Properties) bool { return a.eql(b) }

pub struct SymbolsGeneratorContext {}
pub fn (_ SymbolsGeneratorContext) get(cp u32) !bool {
	return if cp > 0x10ffff { false } else { uucode_buildtime(cp) & 0x100 != 0 }
}
pub fn (_ SymbolsGeneratorContext) eql(a bool, b bool) bool { return a == b }

// V consumes generated byte data rather than an anonymous Zig import. This
// sidecar only changes the compiler storage representation of the LUT arrays.
pub fn write_table_binary[T](self &LutTables[T], path string) ! {
	mut data := []u8{cap: (self.stage1.len + self.stage2.len) * 2 + self.stage3.len}
	for stage in [self.stage1, self.stage2] {
		for value in stage { data << [u8(value), u8(value >> 8)] }
	}
	for value in self.stage3 {
		$if T is Properties { data << value.value }
		$else $if T is bool { data << if value { u8(1) } else { u8(0) } }
		$else { $compile_error('unsupported generated Unicode binary element') }
	}
	os.write_file_array(path, data)!
}
